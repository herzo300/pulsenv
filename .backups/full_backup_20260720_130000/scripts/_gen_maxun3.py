W("def _parse_salary(rows: list[dict]) -> tuple[list[int], list[float]]:")
W('    """Parse average salary dataset into (years, values_thousands)."""')
W("    if not rows:")
W("        return FALLBACK_SALARY_YEARS[:], FALLBACK_SALARY_VALUES[:]")
W("    year_val: dict[int, float] = {}")
W("    for row in rows:")
W('        year_raw = row.get("YEAR") or row.get("year") or row.get("PERIOD", "")')
W('        val_raw = row.get("VALUE") or row.get("SALARY") or row.get("AVG", 0)')
W("        try:")
W("            year = int(str(year_raw)[:4])")
W("            val = float(str(val_raw).replace(\" \", \"\").replace(\",\", \".\"))")
W("        except (ValueError, TypeError):")
W("            continue")
W("        if 2010 <= year <= 2030 and val > 0:")
W("            # Normalize: if value > 1000 it is in rubles, convert to thousands")
W("            if val > 1000:")
W("                val = round(val / 1000, 1)")
W("            year_val[year] = val")
W("    if not year_val:")
W("        return FALLBACK_SALARY_YEARS[:], FALLBACK_SALARY_VALUES[:]")
W("    years = sorted(year_val.keys())")
W("    values = [year_val[y] for y in years]")
W("    return years, values")
W("")
