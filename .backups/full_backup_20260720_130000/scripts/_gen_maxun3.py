W('    """Parse top-names dataset rows into [{name, count}]."""')
W("    if not rows:")
W("        return list(fallback)")
W("    parsed = []")
W("    for row in rows:")
W('        name = row.get("NAME") or row.get("name") or row.get("TITLE", "")')
W('        count_raw = row.get("CNT") or row.get("count") or row.get("VALUE") or row.get("QUANTITY", 0)')
W("        try:")
W("            count = int(float(str(count_raw)))")
W("        except (ValueError, TypeError):")
