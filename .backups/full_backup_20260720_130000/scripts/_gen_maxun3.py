W("def _parse_bus_routes(rows: list[dict]) -> int:")
W('    """Count unique bus routes from busroute dataset."""')
W("    if not rows:")
W("        return FALLBACK_ROUTES_COUNT")
W("    # Each row is a route entry; count unique route numbers")
